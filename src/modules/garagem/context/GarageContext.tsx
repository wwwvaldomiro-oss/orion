import React, { useMemo, useState } from "react";
import { useOrion } from "@/store/orionContext";
import type {
  GarageSnapshot,
  GarageTab,
  PersonalVehicle,
  QuickEntryKind,
  VehicleDocumentRecord,
} from "../types/garage.types";
import { getLicensePlateDueInfo, recalculateFuelingAverages } from "../utils/garage.calculations";
import { GarageContext, type GarageContextValue } from "./garageContext";

export const GarageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const {
    state,
    upsertGarageVehicle,
    deleteGarageVehicle,
    upsertGarageDriver,
    deleteGarageDriver,
    addGarageFueling,
    deleteGarageFueling,
    addGarageMaintenance,
    updateGarageMaintenanceStatus,
    deleteGarageMaintenance,
    addGarageExpense,
    deleteGarageExpense,
    addGarageFine,
    updateGarageFineStatus,
    deleteGarageFine,
    addGarageDocument,
    markGarageDocumentPaid,
    deleteGarageDocument,
    addGarageDocumentsBatch,
    addGarageChecklist,
    addGarageRoute,
    deleteGarageRoute,
    addGarageReminder,
    toggleGarageReminder,
    deleteGarageReminder,
  } = useOrion();

  const [activeTab, setActiveTab] = useState<GarageTab>("dashboard");
  const [selectedVehicleFilter, setSelectedVehicleFilter] = useState<string>("TODOS");
  const [isQuickEntryOpen, setIsQuickEntryOpen] = useState(false);
  const [quickEntryKind, setQuickEntryKind] = useState<QuickEntryKind>("abastecimento");

  const snapshot = useMemo<GarageSnapshot>(() => {
    const vehicles: PersonalVehicle[] = state.vehicles.map((v) => ({
      ...v,
      brand: v.brand || v.name || "Veículo",
      year: v.year || new Date().getFullYear(),
      fuelType: v.fuelType || "FLEX",
      currentOdometer: v.odometerKm || 0,
      status: v.status || "ATIVO",
    }));

    return {
      vehicles,
      drivers: state.garageDrivers,
      fuelings: recalculateFuelingAverages(state.garageFuelings),
      maintenances: state.garageMaintenances,
      expenses: state.garageExpenses,
      fines: state.garageFines,
      documents: state.garageDocuments,
      checklists: state.garageChecklists,
      routes: state.garageRoutes,
      reminders: state.garageReminders,
    };
  }, [state]);

  const openQuickEntry = (kind: QuickEntryKind = "abastecimento") => {
    setQuickEntryKind(kind);
    setIsQuickEntryOpen(true);
  };

  const closeQuickEntry = () => setIsQuickEntryOpen(false);

  const upsertVehicle: GarageContextValue["upsertVehicle"] = async (v) => {
    return upsertGarageVehicle({
      id: v.id,
      name: v.name || `${v.brand} ${v.model}`.trim(),
      plate: v.plate,
      brand: v.brand,
      model: v.model,
      year: v.year,
      fuelType: v.fuelType,
      odometerKm: v.currentOdometer,
      status: v.status,
      assignedDriverId: v.assignedDriverId,
      renavam: v.renavam,
      stateUf: v.stateUf,
      tankCapacityLiters: v.tankCapacityLiters,
      fipeValue: v.fipeValue,
      monthlyFixedCost: v.monthlyFixedCost,
      notes: v.notes,
    });
  };

  const deleteVehicle: GarageContextValue["deleteVehicle"] = async (id) => {
    await deleteGarageVehicle(id);
    if (selectedVehicleFilter === id) {
      setSelectedVehicleFilter("TODOS");
    }
  };

  const generateCalendarForVehicles = async (
    exerciseYear = new Date().getFullYear(),
  ): Promise<number> => {
    const toCreate: Array<Omit<VehicleDocumentRecord, "id">> = [];
    for (const v of snapshot.vehicles) {
      if (v.status === "INATIVO") continue;
      const uf = (v.stateUf || "DF").toUpperCase();
      const cal = getLicensePlateDueInfo(v.plate, uf, exerciseYear);

      const hasIpva = snapshot.documents.some(
        (d) =>
          d.vehicleId === v.id && d.docType === "IPVA" && d.referenceYear === exerciseYear,
      );
      const hasCrlv = snapshot.documents.some(
        (d) =>
          d.vehicleId === v.id && d.docType === "CRLV" && d.referenceYear === exerciseYear,
      );

      if (!hasIpva) {
        const estimatedIpva =
          v.fipeValue && v.fipeValue > 0 ? Number((v.fipeValue * 0.035).toFixed(2)) : 0;
        toCreate.push({
          vehicleId: v.id,
          docType: "IPVA",
          referenceYear: exerciseYear,
          dueDate: cal.ipvaDueDate,
          amount: estimatedIpva,
          stateUf: uf,
          providerOrAuthority: `SEFAZ-${uf}`,
          status: "PENDENTE",
          autoGenerated: true,
          notes:
            estimatedIpva > 0
              ? `Estimativa ~3,5% FIPE · Final ${cal.finalDigit}`
              : `Informe o valor FIPE ou edite o valor do IPVA · Final ${cal.finalDigit}`,
        });
      }

      if (!hasCrlv) {
        toCreate.push({
          vehicleId: v.id,
          docType: "CRLV",
          referenceYear: exerciseYear,
          dueDate: cal.crlvDueDate,
          amount: 160.22,
          stateUf: uf,
          providerOrAuthority: `Detran-${uf}`,
          status: "PENDENTE",
          autoGenerated: true,
          notes: `Licenciamento previsto ${cal.crlvMonthLabel} (taxa média estimada)`,
        });
      }
    }

    if (toCreate.length > 0) {
      await addGarageDocumentsBatch(toCreate);
    }
    return toCreate.length;
  };

  return (
    <GarageContext.Provider
      value={{
        snapshot,
        activeTab,
        setActiveTab,
        selectedVehicleFilter,
        setSelectedVehicleFilter,
        isQuickEntryOpen,
        quickEntryKind,
        openQuickEntry,
        closeQuickEntry,
        upsertVehicle,
        deleteVehicle,
        upsertDriver: upsertGarageDriver,
        deleteDriver: deleteGarageDriver,
        addFueling: addGarageFueling,
        deleteFueling: deleteGarageFueling,
        addMaintenance: addGarageMaintenance,
        updateMaintenanceStatus: updateGarageMaintenanceStatus,
        deleteMaintenance: deleteGarageMaintenance,
        addExpense: addGarageExpense,
        deleteExpense: deleteGarageExpense,
        addFine: addGarageFine,
        updateFineStatus: updateGarageFineStatus,
        deleteFine: deleteGarageFine,
        addDocumentObligation: addGarageDocument,
        markDocumentPaid: markGarageDocumentPaid,
        deleteDocumentObligation: deleteGarageDocument,
        generateCalendarForVehicles,
        addChecklist: addGarageChecklist,
        addRoute: addGarageRoute,
        deleteRoute: deleteGarageRoute,
        addReminder: addGarageReminder,
        toggleReminder: toggleGarageReminder,
        deleteReminder: deleteGarageReminder,
      }}
    >
      {children}
    </GarageContext.Provider>
  );
};
